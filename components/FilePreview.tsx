export default function FilePreview({ files = defaultFiles, title }: FilePreviewProps) {
  const [activeTab, setActiveTab] = useState(0);
  const displayFiles = files && files.length > 0 ? files : defaultFiles;
  const activeFile = displayFiles[activeTab] || displayFiles[0];

  return (
    <div
      style={{
        margin: '1.75rem 0',
        borderRadius: 'var(--radius-lg)',
        background: 'var(--code-bg)',
        border: '1px solid var(--border-subtle)',
        overflow: 'hidden',
        boxShadow: 'var(--shadow-panel)',
      }}
    >
      {/* Tab Header */}
      <div
        style={{
          display: 'flex',
          flexWrap: 'wrap',
          alignItems: 'center',
          justifyContent: 'space-between',
          padding: '0.5rem 0.85rem',
          background: 'rgba(0, 0, 0, 0.35)',
          borderBottom: '1px solid var(--border-subtle)',
          gap: '0.5rem',
        }}
      >
        <div style={{ display: 'flex', alignItems: 'center', gap: '0.4rem' }}>
          {files.map((file, idx) => (
            <button
              key={file.name}
              onClick={() => setActiveTab(idx)}
              style={{
                display: 'inline-flex',
                alignItems: 'center',
                gap: '0.4rem',
                padding: '0.35rem 0.75rem',
                borderRadius: 'var(--radius-sm)',
                fontSize: '0.82rem',
                fontWeight: activeTab === idx ? 600 : 500,
                background:
                  activeTab === idx
                    ? 'rgba(255, 122, 24, 0.15)'
                    : 'transparent',
                color:
                  activeTab === idx
                    ? 'var(--accent-orange)'
                    : 'var(--text-secondary)',
                border:
                  activeTab === idx
                    ? '1px solid rgba(255, 122, 24, 0.3)'
                    : '1px solid transparent',
                cursor: 'pointer',
                transition: 'all 0.15s ease',
              }}
            >
              <FileText size={14} />
              <span>{file.name}</span>
            </button>
          ))}
        </div>

        <div
          style={{
            fontSize: '0.75rem',
            color: 'var(--accent-cyan)',
            padding: '0.2rem 0.5rem',
            borderRadius: '4px',
            background: 'rgba(0, 210, 255, 0.08)',
            border: '1px solid rgba(0, 210, 255, 0.2)',
          }}
        >
          {activeFile.kind}
        </div>
      </div>

      {/* Annotation Box */}
      {activeFile.annotation && (
        <div
          style={{
            padding: '0.75rem 1rem',
            background: 'rgba(255, 255, 255, 0.02)',
            borderBottom: '1px solid var(--border-subtle)',
            fontSize: '0.85rem',
            color: 'var(--text-secondary)',
            display: 'flex',
            alignItems: 'center',
            gap: '0.5rem',
          }}
        >
          <Layers size={14} style={{ color: 'var(--accent-orange)' }} />
          <span>{activeFile.annotation}</span>
        </div>
      )}

      {/* Code Area */}
      <div style={{ padding: '1rem', overflowX: 'auto' }}>
        <pre style={{ margin: 0, background: 'transparent', color: '#e2e8f0', fontSize: '0.88rem', lineHeight: 1.6 }}>
          <code>{activeFile.code}</code>
        </pre>
      </div>
    </div>
  );
}
